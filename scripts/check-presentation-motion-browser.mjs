import assert from 'node:assert/strict';
import fs from 'node:fs';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
 await page.goto(process.env.INNSIKT_BASE_URL||'http://127.0.0.1:19765/docs/',{waitUntil:'networkidle'});
 await page.locator('#present-button').click();
 const frame=page.locator('#slide-body');
 assert.equal(await page.locator('#present-motion-mode').inputValue(),'on');
 assert.equal(await frame.getAttribute('data-motion'),'on');
 assert.match(await frame.locator('.scene-analysts-number').evaluate(el=>getComputedStyle(el).animationName),/insight-float-in/);
 await page.locator('#present-motion-mode').selectOption('off');
 assert.equal(await frame.getAttribute('data-motion'),'off');
 assert.equal(await frame.locator('.scene-analysts-number').evaluate(el=>getComputedStyle(el).animationName),'none');
 await page.locator('#slide-next').click();
 await page.locator('#slide-next').click();
 assert.equal(await frame.getAttribute('data-transition'),'fade');
 assert.equal(await frame.locator('.v14-market-stat strong').innerText(),'48 %');
 assert.equal(await frame.locator('.v14-market-trend').count(),3);
 await page.locator('#slide-next').click();await page.locator('#slide-next').click();
 assert.equal(await frame.getAttribute('data-transition'),'reveal');
 assert.equal(await frame.locator('.scene-duality-editorial').count(),1);
 assert.equal(await frame.locator('.scene-editorial-outcomes h3').count(),2);
 await page.locator('#present-motion-mode').selectOption('on');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await frame.locator('.scene-editorial-risk').evaluate(el=>getComputedStyle(el).animationName),'none','System reduced-motion must override motion enabled');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.locator('[data-deck="portal"]').click();
 assert.equal(await frame.getAttribute('data-motion'),'on','Motion kept across stories');
 await page.locator('#present-tone-mode').selectOption('light');
 await page.locator('#present-motion-mode').selectOption('off');
 await page.evaluate(()=>{const s=document.createElement('style');s.setAttribute('data-innsikt-skin','');s.textContent=':root{--slide-light-bg:#123456;--slide-light-fg:#ffffff}';document.head.append(s)});
 const [dl]=await Promise.all([page.waitForEvent('download'),page.locator('#deck-download').click()]);
 const html=fs.readFileSync(await dl.path(),'utf8');
 assert.ok(html.includes('--slide-light-bg:#123456'),'Org CSS must be embedded');
 assert.ok(html.includes('id="export-motion"'),'Offline motion switch');
 assert.ok(html.includes('data-motion="off"'),'Export honors selection');
 const offline=await browser.newPage({viewport:{width:1280,height:900}});
 await offline.setContent(html);
 assert.equal(await offline.locator('#export-motion').getAttribute('aria-pressed'),'false');
 await offline.locator('#export-motion').click();
 assert.equal(await offline.locator('#export-motion').getAttribute('aria-pressed'),'true');
 assert.equal(await offline.locator('.export-slide').first().getAttribute('data-motion'),'on');
 await offline.emulateMedia({media:'print'});
 assert.equal(await offline.locator('.export-slide').first().evaluate(el=>getComputedStyle(el).animationName),'none');
 await offline.close();
 await page.keyboard.press('Escape');
 await page.evaluate(()=>{location.hash='#lysbilder/ai-thousand-analysts'});
 await page.locator('.slide-library-detail-stage .scene-analysts-number').waitFor();
 assert.equal(await page.locator('.slide-library-detail-stage .scene-analysts-number').evaluate(el=>getComputedStyle(el).animationName),'none');
 console.log('PASS – standalone slides, motion on/off, per-story transitions, reduced motion, skinnable offline export and static library');
}finally{await browser.close()}
